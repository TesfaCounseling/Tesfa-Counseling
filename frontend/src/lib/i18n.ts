export type TranslationKey = keyof typeof en;

export const translations: Record<AppLanguage, Record<TranslationKey, string>> = { en, am };

export function isAppLanguage(value: string | null | undefined): value is AppLanguage {
  return value === "en" || value === "am";
}

export function getStoredLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return isAppLanguage(stored) ? stored : "en";
}

export function translate(lang: AppLanguage, key: TranslationKey): string {
  return translations[lang][key] ?? translations.en[key] ?? key;
}

export function formatTranslation(
  lang: AppLanguage,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  let text = translate(lang, key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{\\{${name}\\}\\}`, "g"), String(value));
    }
  }
  return text;
}
